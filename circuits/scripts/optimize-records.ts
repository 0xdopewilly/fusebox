/**
 * Runs the gate-golf optimizer over every circuit Fusebox ships or has designed, plus rules people typically write in
 * Fuse Studio, and writes the results (and the gas-per-gate model) to web/lib/circuits/optimize-records.json for the
 * Studio page.
 *
 *   node circuits/scripts/optimize-records.ts
 */
import { writeFileSync } from "node:fs";
import { Builder, add, lessOrEqual, majority3, ONE, ZERO, type Netlist, type Sig } from "../src/builder.ts";
import { FUSES } from "../src/fuses.ts";
import { RIVALS } from "../src/rivals.ts";
import { optimize } from "../src/optimize.ts";

// Gas per check measured for the four shipped fuses (web/lib/fuses.ts, FUSE_META chips) against their gate counts.
const MEASURED: [string, number, number][] = [["Daily Cap", 108, 283_000], ["Payee Guard", 79, 211_000], ["Breaker", 11, 50_000], ["Two of Three", 46, 132_000]];
const n = MEASURED.length, mx = MEASURED.reduce((t, m) => t + m[1], 0) / n, my = MEASURED.reduce((t, m) => t + m[2], 0) / n;
const perGate = MEASURED.reduce((t, m) => t + (m[1] - mx) * (m[2] - my), 0) / MEASURED.reduce((t, m) => t + (m[1] - mx) ** 2, 0);
const base = my - perGate * mx;

const konst = (k: number): Sig[] => Array.from({ length: 8 }, (_, i) => ((k >> i) & 1 ? ONE : ZERO));
const s1 = (f: (b: Builder, p: { spent: Sig[]; amount: Sig[]; cap: Sig[] }) => Sig): Netlist => { const b = new Builder(24); return b.build("r", [f(b, { spent: b.bus(0, 8), amount: b.bus(8, 8), cap: b.bus(16, 8) })]); };
const s4 = (f: (b: Builder, p: { amount: Sig[]; threshold: Sig[]; ap: Sig[] }) => Sig): Netlist => { const b = new Builder(19); return b.build("r", [f(b, { amount: b.bus(0, 8), threshold: b.bus(8, 8), ap: b.bus(16, 3) })]); };
const total = (b: Builder, p: { spent: Sig[]; amount: Sig[]; cap: Sig[] }) => { const t = add(b, p.spent, p.amount); return b.and(b.not(t.carry), lessOrEqual(b, t.sum, p.cap)); };
const EXAMPLES: [string, Netlist][] = [
  ["Today's total within the cap and this payment within the cap", s1((b, p) => b.and(total(b, p), lessOrEqual(b, p.amount, p.cap)))],
  ["This payment within the cap and within half the cap", s1((b, p) => b.and(lessOrEqual(b, p.amount, p.cap), lessOrEqual(b, p.amount, [...p.cap.slice(1), ZERO])))],
  ["At most 100 USD₮0 and at most 50 USD₮0", s1((b, p) => b.and(lessOrEqual(b, p.amount, konst(100)), lessOrEqual(b, p.amount, konst(50))))],
  ["Today's total within the cap and at most 100 USD₮0", s1((b, p) => b.and(total(b, p), lessOrEqual(b, p.amount, konst(100))))],
  ["Under the threshold, or seat 1 and two of three signed (Studio's default)", s4((b, p) => b.or(lessOrEqual(b, p.amount, p.threshold), b.and(p.ap[0], majority3(b, p.ap[0], p.ap[1], p.ap[2]).maj)))],
  ["At most 50, or at most 20 with two of three signed", s4((b, p) => b.or(lessOrEqual(b, p.amount, konst(50)), b.and(lessOrEqual(b, p.amount, konst(20)), majority3(b, p.ap[0], p.ap[1], p.ap[2]).maj)))],
];

const row = (title: string, net: Netlist, extra: Record<string, unknown> = {}) => {
  const r = optimize(net);
  const out = { title, ...extra, nand: net.nand, latch: net.latch, gates: net.gates, optimized: r.net.gates, improved: r.improved, proof: r.proof ? { method: r.proof.method, assignments: r.proof.assignments } : null };
  console.log(`${title.padEnd(72)} ${String(net.gates).padStart(4)} -> ${String(r.net.gates).padStart(4)} ${r.improved ? `(${r.proof?.method})` : "minimal"}`);
  return out;
};
const ours = [
  ...FUSES.map((f, i) => row(f.title, f.build(), { kind: "shipped", circuit: 15 + i, socket: f.socket.id })),
  ...RIVALS.map((f) => row(f.title, f.build(), { kind: "rival", socket: f.socket.id })),
];
const examples = EXAMPLES.map(([t, net]) => row(t, net, { kind: "example" }));
const out = {
  note: "Generated by circuits/scripts/optimize-records.ts. Gates as built vs after the optimizer, each smaller circuit proved equivalent on every input.",
  gasModel: { base: Math.round(base), perGate: Math.round(perGate), measured: MEASURED.map(([name, gates, gas]) => ({ name, gates, gas })), source: "gas per check of the four shipped fuses (FUSE_META), least-squares fit; a full four-fuse payment measured 956,528 gas on X Layer mainnet (tx 0x058bd5eb…1f94), the rest being the wallet's own transfer and bookkeeping" },
  ours, examples,
};
writeFileSync(new URL("../../web/lib/circuits/optimize-records.json", import.meta.url), JSON.stringify(out, null, 1) + "\n");
console.log(`gas model: ${Math.round(base)} + ${Math.round(perGate)} per gate`);

// Ships the ready-made rules (web/lib/studioLibrary.json) to the SDK (sdk/src/rules.ts) and the MCP server
// (mcp/rules.json), with each rule's Studio link, so an agent can ask for a rule by name.
// Edit studioLibrary.json, then run: node web/scripts/sync-rules.mjs
import { readFileSync, writeFileSync } from "node:fs";

const APP = "https://fusebox-xlayer.vercel.app";
const lib = JSON.parse(readFileSync(new URL("../lib/studioLibrary.json", import.meta.url), "utf8"));
const SOCKET = { 1: "Daily Cap", 2: "Payee Guard", 3: "Breaker", 4: "Two of Three", 5: "Repeat Guard" };

// Studio's draft link, encoded exactly as web/lib/studio.ts encodeDraft does
function draft(r, name) {
  const opOf = (i) => r.ops?.[i] ?? { m: "all", k: 0 };
  const join = r.join ?? "any";
  const plain = !r.ops?.some((o) => o.m !== "all") && join === "any";
  const json = JSON.stringify({ s: r.socket, g: r.groups.map((g) => g.map((c) => [c.kind, c.k])), n: r.strikes, name: name.slice(0, 40), ...(plain ? {} : { o: r.groups.map((_, i) => [opOf(i).m, opOf(i).k]), j: join }) });
  return Buffer.from(json, "utf8").toString("base64").replace(/\+/g, "-").replace(/\//g, "_").replace(/=+$/, "");
}

const rules = lib.map((t) => ({
  id: t.id,
  name: t.name,
  when: t.when,
  socket: t.rule.socket,
  socketName: SOCKET[t.rule.socket],
  ...(t.fuse ? { fuseId: t.fuse } : {}),
  studio: `${APP}/app/studio?draft=${draft(t.rule, t.name)}`,
}));

writeFileSync(new URL("../../mcp/rules.json", import.meta.url), JSON.stringify(rules, null, 1) + "\n");
writeFileSync(
  new URL("../../sdk/src/rules.ts", import.meta.url),
  `// Generated by web/scripts/sync-rules.mjs from web/lib/studioLibrary.json. Edit that, then rerun the script.
/** A ready-made rule from Fuse Studio's library. */
export interface RuleTemplate {
  id: string;
  name: string;
  /** who reaches for it, in plain words */
  when: string;
  /** the socket its circuit plugs into (1 Daily Cap, 2 Payee Guard, 3 Breaker, 4 Two of Three, 5 Repeat Guard) */
  socket: number;
  socketName: string;
  /** the live v2 fuse with exactly this circuit: a wallet can install it now, with nothing to tape out */
  fuseId?: number;
  /** opens the rule in Fuse Studio, to prove it, change it or tape it out */
  studio: string;
}

export const RULES: RuleTemplate[] = ${JSON.stringify(rules, null, 1)};
`,
);
console.log(`synced ${rules.length} rules (${rules.filter((r) => r.fuseId).length} live) to sdk/src/rules.ts and mcp/rules.json`);
